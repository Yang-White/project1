const list = document.querySelector("#article-list");
if (list) {
  const filters = [...document.querySelectorAll(".filter-chip")];

  articles.filter((article) => article.id !== "featured").forEach((article) => {
    const card = document.createElement("article");
    card.className = "article-card";
    card.dataset.category = article.category;
    card.innerHTML = `
      <a class="card-image" href="article.html?id=${article.id}">
        <img src="${article.image}" alt="${article.alt}">
        <span class="tag ${article.tagClass}">${article.label}</span>
        <span class="card-image-icon" aria-hidden="true">↗</span>
      </a>
      <div class="card-body">
        <div class="card-meta"><span>${article.meta}</span><span>${article.date}</span></div>
        <h2><a href="article.html?id=${article.id}">${article.title}</a></h2>
        <p>${article.summary}</p>
        <a class="read-more" href="article.html?id=${article.id}">閱讀全文 <span>→</span></a>
      </div>`;
    list.append(card);
  });

  filters.forEach((button) => {
    button.addEventListener("click", () => {
      const category = button.dataset.category;
      filters.forEach((filter) => {
        const isActive = filter === button;
        filter.classList.toggle("active", isActive);
        filter.setAttribute("aria-pressed", String(isActive));
      });
      list.querySelectorAll(".article-card").forEach((card) => {
        card.hidden = category !== "全部" && card.dataset.category !== category;
      });
    });
  });
}

const detail = document.querySelector("#article-detail");
if (detail) {
  const article = articles.find((item) => item.id === new URLSearchParams(location.search).get("id"));
  if (article) {
    document.title = `${article.title}｜像素情報站`;
    document.querySelector('meta[name="description"]').content = article.summary;
    detail.innerHTML = `
      <img class="article-detail-image" src="${article.image}" alt="${article.alt}">
      <p class="eyebrow">${article.label}</p>
      <h1>${article.title}</h1>
      <div class="article-detail-meta"><span>${article.meta}</span><time>${article.date}</time></div>
      <p class="article-detail-summary">${article.summary}</p>
      <div class="article-detail-body"></div>`;
    const body = detail.querySelector(".article-detail-body");
    article.body.forEach((paragraph) => {
      const element = document.createElement("p");
      element.textContent = paragraph;
      body.append(element);
    });
  } else {
    detail.innerHTML = `
      <p class="eyebrow">PIXEL PRESS</p>
      <h1>找不到這篇文章</h1>
      <p>文章連結可能已失效，請回到文章列表瀏覽其他內容。</p>
      <a class="button button-primary" href="articles.html">瀏覽文章 <span aria-hidden="true">↗</span></a>`;
  }
}
